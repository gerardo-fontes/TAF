import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import { query, getPool } from '../pool';
import { computeComparison, getCandidateBaselines } from './compare';

describe('computeComparison Parity with TAF do_compare()', () => {
  beforeAll(async () => {
    // Ensure pool is reachable
    const [alive] = await query<any[]>('SELECT 1 AS alive;');
    expect(alive).toBeDefined();
  });

  afterAll(async () => {
    const p = getPool();
    await p.end();
  });

  it('matches MariaDB native do_compare() rows on all seeded comparisons', async () => {
    const storedComparisons = await query<any[]>(
      `SELECT
         id,
         baseline_run_id,
         candidate_run_id,
         status,
         thread_of_max_change,
         max_change_pct,
         max_change_value
       FROM test_run_comparison
       ORDER BY id ASC;`
    );

    // Verify that our seed script populated at least 3 comparison rows
    expect(storedComparisons.length).toBeGreaterThanOrEqual(3);

    for (const stored of storedComparisons) {
      const computed = await computeComparison(
        String(stored.baseline_run_id),
        String(stored.candidate_run_id)
      );

      // 1. Status classification parity (GAIN / REGRESSED / WARNING)
      expect(computed.status).toBe(stored.status);

      // 2. Thread of maximum change parity
      expect(computed.threadOfMaxChange).toBe(Number(stored.thread_of_max_change));

      // 3. Max change percentage parity (floating point precision tolerance)
      expect(computed.maxChangePct).toBeCloseTo(Number(stored.max_change_pct), 2);

      // 4. Raw change value parity
      expect(computed.maxChangeValue).toBeCloseTo(Number(stored.max_change_value), 1);

      // 5. Must be flagged as compatible
      expect(computed.compatible).toBe(true);
    }
  });

  it('enforces the workload_hash incompatibility guard for mismatched workloads', async () => {
    // Run #1 is TPCC on EPYC
    // Run #5 is TPCC Scale 200 on Xeon (intentionally different workload_hash)
    const [runs] = await query<any[]>(
      `SELECT
         (SELECT id FROM test_run WHERE is_baseline = TRUE LIMIT 1) AS baseline_id,
         (SELECT id FROM test_run WHERE test_case_tag = 'TPCC_SCALE_200_INCOMPATIBLE' LIMIT 1) AS incompatible_id;`
    );

    if (runs?.baseline_id && runs?.incompatible_id) {
      const result = await computeComparison(String(runs.baseline_id), String(runs.incompatible_id));

      expect(result.compatible).toBe(false);
      expect(result.incompatibleReason).toContain('Workloads are incompatible');
      expect(result.rows).toHaveLength(0);
    }
  });

  it('retrieves candidate baselines for a candidate run', async () => {
    const [candidate] = await query<any[]>(
      `SELECT id FROM test_run WHERE test_case_tag = 'MDEV39497_PATCH_GAIN' LIMIT 1;`
    );

    if (candidate) {
      const baselines = await getCandidateBaselines(String(candidate.id));
      expect(baselines.length).toBeGreaterThanOrEqual(1);
      expect(baselines[0].isBaseline).toBe(true);
      expect(baselines[0].testCaseTag).toBe('MDEV39497_BASELINE');
    }
  });

  it('allows forced comparison on incompatible workloads when force=true', async () => {
    const [runs] = await query<any[]>(
      `SELECT
         (SELECT id FROM test_run WHERE is_baseline = TRUE LIMIT 1) AS baseline_id,
         (SELECT id FROM test_run WHERE test_case_tag = 'TPCC_SCALE_200_INCOMPATIBLE' LIMIT 1) AS incompatible_id;`
    );

    if (runs?.baseline_id && runs?.incompatible_id) {
      const result = await computeComparison(String(runs.baseline_id), String(runs.incompatible_id), { force: true });
      expect(result.compatible).toBe(false);
      expect(result.incompatibleReason).toBeDefined();
      // Rows should still be computed in force mode
      expect(result.rows.length).toBeGreaterThan(0);
    }
  });

  it('honors dynamic threshold overrides in comparison computation', async () => {
    // Run 1 vs Run 2 is GAIN with default +5% threshold.
    // Overriding pctGain to +50% should turn the status into PAR+!
    const [stored] = await query<any[]>(
      `SELECT baseline_run_id, candidate_run_id FROM test_run_comparison WHERE status = 'GAIN' LIMIT 1;`
    );

    if (stored) {
      const custom = await computeComparison(
        String(stored.baseline_run_id),
        String(stored.candidate_run_id),
        { thresholds: { pctGain: 50 } }
      );
      expect(custom.status).toBe('PAR+');
      expect(custom.thresholds.pctGain).toBe(50);
    }
  });
});
